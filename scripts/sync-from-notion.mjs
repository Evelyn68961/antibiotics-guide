// Pulls every antibiotic from your Notion database and writes them
// to src/data/antibiotics.js. Notion is the source of truth.
//
// Setup:
//   1. Create a Notion integration at https://www.notion.so/my-integrations
//   2. Open your "Antimicrobial List" database in Notion → Settings →
//      "Connections" → add the integration you created
//   3. Copy .env.example to .env and fill in NOTION_TOKEN and
//      NOTION_DATABASE_ID
//   4. Run: npm run sync-notion

import 'dotenv/config'
import { Client } from '@notionhq/client'
import { NotionToMarkdown } from 'notion-to-md'
import { writeFileSync, mkdirSync } from 'node:fs'
import { dirname, resolve } from 'node:path'
import { fileURLToPath } from 'node:url'

const __dirname = dirname(fileURLToPath(import.meta.url))
const OUTPUT_PATH = resolve(__dirname, '..', 'src', 'data', 'antibiotics.js')

const token = process.env.NOTION_TOKEN
const databaseId = process.env.NOTION_DATABASE_ID

if (!token) {
  console.error('Error: NOTION_TOKEN is missing. See .env.example.')
  process.exit(1)
}
if (!databaseId) {
  console.error('Error: NOTION_DATABASE_ID is missing. See .env.example.')
  process.exit(1)
}

const notion = new Client({ auth: token })
const n2m = new NotionToMarkdown({ notionClient: notion })

// ------- Property extraction helpers -------

function extractText(prop) {
  if (!prop) return ''
  if (prop.type === 'title') {
    return prop.title.map((t) => t.plain_text).join('').trim()
  }
  if (prop.type === 'rich_text') {
    return prop.rich_text.map((t) => t.plain_text).join('').trim()
  }
  return ''
}

function extractMultiSelect(prop) {
  if (!prop || prop.type !== 'multi_select') return []
  return prop.multi_select.map((o) => o.name)
}

function extractDate(prop) {
  if (!prop || prop.type !== 'date' || !prop.date) return null
  return prop.date.start
}

// "Cubicin (Daptomycin)" → { brand: "Cubicin", generic: "Daptomycin" }
// "Meropenem"            → { brand: null,      generic: "Meropenem" }
function parseName(fullName) {
  const match = fullName.match(/^(.+?)\s*\((.+)\)\s*$/)
  if (match) return { brand: match[1].trim(), generic: match[2].trim() }
  return { brand: null, generic: fullName.trim() }
}

// ------- Notion fetching -------

async function queryAllPages() {
  const pages = []
  let cursor
  do {
    const resp = await notion.databases.query({
      database_id: databaseId,
      start_cursor: cursor,
      page_size: 100,
    })
    pages.push(...resp.results)
    cursor = resp.has_more ? resp.next_cursor : undefined
  } while (cursor)
  return pages
}

async function pageToMarkdown(pageId) {
  try {
    const blocks = await n2m.pageToMarkdown(pageId)
    const md = n2m.toMarkdownString(blocks)
    return (md.parent || '').trim()
  } catch (err) {
    console.warn(`  Could not fetch monograph for ${pageId}: ${err.message}`)
    return ''
  }
}

// ------- Main -------

async function main() {
  console.log('Fetching pages from Notion…')
  const pages = await queryAllPages()
  console.log(`Found ${pages.length} page(s).\n`)

  const records = []
  for (let i = 0; i < pages.length; i++) {
    const page = pages[i]
    const props = page.properties || {}
    const fullName = extractText(props['Abx'])
    if (!fullName) {
      console.log(`  [${i + 1}/${pages.length}] (skipped — no Abx title)`)
      continue
    }
    const { brand, generic } = parseName(fullName)
    process.stdout.write(`  [${i + 1}/${pages.length}] ${fullName}… `)

    const monograph = await pageToMarkdown(page.id)

    records.push({
      id: page.id,
      name: fullName,
      brandName: brand,
      genericName: generic,
      category: extractText(props['Category']),
      coverage: extractMultiSelect(props['Coverage']),
      indications: extractMultiSelect(props['Indications']),
      adultDose: extractText(props['Adult dose']),
      pediatricDose: extractText(props['Pediatric dose']),
      renalDose: extractText(props['Renal dose, HD, CRRT']),
      hepaticDose: extractText(props['Hepatic dose']),
      pregnancy: extractText(props['Pregnancy']),
      breastfeeding: extractText(props['Breastfeeding']),
      mechanism: extractText(props['Mechanism']),
      drugInteractions: extractText(props['Drug Interactions']),
      sideEffects: extractMultiSelect(props['Side Effects']),
      monitor: extractMultiSelect(props['Monitor']),
      notes: extractText(props['Notes']),
      renewedDate: extractDate(props['Renewed date']),
      monograph,
      url: page.url,
    })
    console.log('done')
  }

  // Sort alphabetically by generic name for stable output
  records.sort((a, b) => a.genericName.localeCompare(b.genericName))

  const banner =
    '// AUTO-GENERATED by scripts/sync-from-notion.mjs — DO NOT EDIT BY HAND.\n' +
    '// Source: Notion database (NOTION_DATABASE_ID).\n' +
    `// Last sync: ${new Date().toISOString()}\n` +
    '// To update: edit in Notion, then run `npm run sync-notion`.\n\n'
  const body =
    `const antibiotics = ${JSON.stringify(records, null, 2)}\n\n` +
    'export default antibiotics\n'

  mkdirSync(dirname(OUTPUT_PATH), { recursive: true })
  writeFileSync(OUTPUT_PATH, banner + body, 'utf8')
  console.log(`\nWrote ${records.length} record(s) to ${OUTPUT_PATH}`)
}

main().catch((err) => {
  console.error('\nSync failed:', err)
  process.exit(1)
})
